/**
 *       \file       ajax/eppo_search.php
 *       \brief      Search of the EPPO Codes imported in doliFarm (select2 format)
 */

if (!defined('NOTOKENRENEWAL')) {
	define('NOTOKENRENEWAL', 1); // Disables token renewal
}
if (!defined('NOREQUIREMENU')) {
	define('NOREQUIREMENU', '1');
}
if (!defined('NOREQUIREHTML')) {
	define('NOREQUIREHTML', '1');
}
if (!defined('NOREQUIREAJAX')) {
	define('NOREQUIREAJAX', '1');
}
if (!defined('NOREQUIRESOC')) {
	define('NOREQUIRESOC', '1');
}
if (!defined('NOCSRFCHECK')) {
	define('NOCSRFCHECK', '1');
}
if (!defined('NOREQUIREHTML')) {
	define('NOREQUIREHTML', '1');
}

// Load Dolibarr environment
$res = 0;
// Try main.inc.php into web root known defined into CONTEXT_DOCUMENT_ROOT (not always defined)
if (!$res && !empty($_SERVER["CONTEXT_DOCUMENT_ROOT"])) {
	$res = @include $_SERVER["CONTEXT_DOCUMENT_ROOT"]."/main.inc.php";
}
// Try main.inc.php into web root detected using web root calculated from SCRIPT_FILENAME
$tmp = empty($_SERVER['SCRIPT_FILENAME']) ? '' : $_SERVER['SCRIPT_FILENAME'];
$tmp2 = realpath(__FILE__);
$i = strlen($tmp) - 1;
$j = strlen($tmp2) - 1;
while ($i > 0 && $j > 0 && isset($tmp[$i]) && isset($tmp2[$j]) && $tmp[$i] == $tmp2[$j]) {
	$i--;
	$j--;
}
if (!$res && $i > 0 && file_exists(substr($tmp, 0, ($i + 1))."/main.inc.php")) {
	$res = @include substr($tmp, 0, ($i + 1))."/main.inc.php";
}
if (!$res && $i > 0 && file_exists(dirname(substr($tmp, 0, ($i + 1)))."/main.inc.php")) {
	$res = @include dirname(substr($tmp, 0, ($i + 1)))."/main.inc.php";
}
// Try main.inc.php using relative path
if (!$res && file_exists("../../main.inc.php")) {
	$res = @include "../../main.inc.php";
}
if (!$res && file_exists("../../../main.inc.php")) {
	$res = @include "../../../main.inc.php";
}
if (!$res) {
	http_response_code(500);
	die("Include of main fails");
}

/**
 * @var DoliDB $db
 * @var Translate $langs
 * @var User $user
 */

dol_include_once('/dolifarm/lib/dolifarm_eppo.lib.php');

$term = GETPOST('term', 'alphanohtml');
$use = GETPOST('use', 'aZ09');

// Security check: the EPPO Codes are used by the crops (doliFarm) and the pests (doliTrace)
if (!isModEnabled('dolifarm') || empty($user->id)) {
	httponly_accessforbidden('Module dolifarm not enabled or not logged');
}

$langs->load('dolifarm@dolifarm');
$datatypes = dolifarmEppoDatatypes();

top_httphead('application/json');

$results = dolifarmEppoSearch($db, $term, isset($datatypes[$use]) ? $datatypes[$use] : array());
if ($results === false) {
	http_response_code(500);
	print json_encode(array('results' => array()));
} else {
	print json_encode(array('results' => array_values($results)));
}

$db->close();
